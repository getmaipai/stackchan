#!/usr/bin/env python3
"""Cut the unit's own grid-game drawing out of maipai_grid.cc (the Grid struct, the draw callbacks, build and redraw) into a header the host
program scripts/fw-face-render/grid_render.cc includes, so the Four in a Row board, Memory Match cards, Hangman and Mine Finder are drawn by the unit's code.
Usage: grid_gen.py <firmware tree root> <out dir>. Fails loudly when the markers moved. Placement: host-side development tool. Upstream: none."""
import sys
from pathlib import Path

tree, out = Path(sys.argv[1]), Path(sys.argv[2])
src = (tree / "firmware/main/hal/maipai_grid.cc").read_text()


def between(a, b, incl_b=False):
    i = src.index(a)
    j = src.index(b, i)
    return src[i:j + (len(b) if incl_b else 0)]


try:
    head = between("enum { kC4", "\n};\n\nGrid* s_grid", incl_b=False) + "\n};\n"
    draw = between("lv_color_t rgb(uint32_t c)", "// Patch SF72: the grid games' sounds")
except ValueError as e:
    sys.exit("grid_gen: the markers in maipai_grid.cc moved (%s). Update scripts/virtual-unit/grid_gen.py." % e)
# the Info table and word lists sit between the enum and the struct: the host program does not need them
head = head.replace(head[head.index("struct Info"):head.index("struct Grid")], "")
text = """// generated by scripts/virtual-unit/grid_gen.py from maipai_grid.cc: do not edit
#pragma once
namespace {
uint32_t now_ms();
%s
Grid* s_grid = nullptr;
%s
}  // namespace
""" % (head, draw)
out.mkdir(parents=True, exist_ok=True)
(out / "grid_draw_gen.h").write_text(text)
print("wrote", out / "grid_draw_gen.h")
