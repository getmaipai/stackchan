#!/usr/bin/env python3
"""Intent: make the bench speech clips (patch L06) and embed them as firmware/main/hal/maipai_bench_clips.c.
Needs macOS `say` and ffmpeg. Usage: python3 scripts/fw-bench-clips.py [TREE_FIRMWARE_DIR]. The output is a build input, never committed."""
import os, struct, subprocess, sys, tempfile

TEXTS = ["Hi, Stack Chan", "What is two plus two?", "What color is the sky on a clear day?",
         "How many days are in a week?", "What is the capital of France?", "Name an animal that lives in the ocean."]
fw = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware")
tmp = tempfile.mkdtemp()
blob, offs = b"", []
for i, text in enumerate(TEXTS):
    aiff = os.path.join(tmp, f"c{i}.aiff")
    subprocess.run(["say", "-v", "Samantha", "-o", aiff, text], check=True)
    pcm = subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", aiff, "-ar", "16000", "-ac", "1", "-af",
                          "silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse",
                          "-f", "s16le", "-"], check=True, capture_output=True).stdout
    offs.append((len(blob) // 2, len(pcm) // 2)); blob += pcm
# clip 6: eight seconds of pink noise (the fan test)
noise = subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-f", "lavfi", "-i",
                        "anoisesrc=color=pink:amplitude=0.5:duration=8:sample_rate=16000:seed=7", "-af",
                        "lowpass=f=3500,highpass=f=60", "-f", "s16le", "-"], check=True, capture_output=True).stdout
offs.append((len(blob) // 2, len(noise) // 2)); blob += noise
vals = struct.unpack("<%dh" % (len(blob) // 2), blob)
out = ["/* generated by scripts/fw-bench-clips.py: bench-only speech clips */", "#include <sdkconfig.h>", "#include <stdint.h>",
       "#ifdef CONFIG_MAIPAI_SERIAL_TOOLS", f"const int g_bench_clip_count={len(offs)};",
       "const uint32_t g_bench_clip_off[]={%s};" % ",".join(str(o) for o, _ in offs),
       "const uint32_t g_bench_clip_len[]={%s};" % ",".join(str(l) for _, l in offs),
       f"const int16_t g_bench_clips[{len(vals)}]={{"]
for i in range(0, len(vals), 24):
    out.append(",".join(map(str, vals[i:i + 24])) + ",")
out += ["};", "#endif"]
open(os.path.join(fw, "main/hal/maipai_bench_clips.c"), "w").write("\n".join(out) + "\n")
