#!/usr/bin/env python3
# Intent: write docs/dev/third-party-indirect.md, the license of every package in host/uv.lock that host/pyproject.toml does not name itself.
# Licenses come from each package's own installed metadata (host/.venv: run `uv sync` first); the license text is never restated.
# Usage: python3 scripts/third-party-indirect.py   (regenerates the table; scripts/license-check.py fails when a lock package has no row)
# Placement: repo tool. Upstream: none.
import re
import sys
import tomllib
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "dev" / "third-party-indirect.md"


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def direct_names() -> set[str]:
    project = tomllib.loads((ROOT / "host" / "pyproject.toml").read_text())
    deps = list(project["project"]["dependencies"])
    for group in project["project"].get("optional-dependencies", {}).values():
        deps += group
    for group in project.get("dependency-groups", {}).values():
        deps += [d for d in group if isinstance(d, str)]
    return {norm(re.split(r"[<>=\[ ;~!]", d, maxsplit=1)[0]) for d in deps}


def lock_packages() -> dict[str, str]:
    lock = tomllib.loads((ROOT / "host" / "uv.lock").read_text())
    return {norm(p["name"]): p.get("version", "") for p in lock["package"] if norm(p["name"]) != "maipai-bot"}


def indirect() -> dict[str, str]:
    direct = direct_names()
    return {n: v for n, v in sorted(lock_packages().items()) if n not in direct}


# For packages whose wheel carries no license metadata here (not installed in this environment, or no field). Well known upstream licenses only; anything
# else stays "to confirm upstream" and is listed as an open item in THIRD-PARTY.md.
KNOWN = {
    "absl-py": "Apache-2.0", "cloudpickle": "BSD-3-Clause", "etils": "Apache-2.0", "glfw": "MIT", "joblib": "BSD-3-Clause", "mujoco": "Apache-2.0",
    "narwhals": "MIT", "zipp": "MIT", "pyopengl": "BSD-3-Clause", "scikit-learn": "BSD-3-Clause", "threadpoolctl": "BSD-3-Clause",
}


def license_of(name: str) -> str:
    found = _declared(name)
    if found.startswith(("not installed", "see the package")):
        return KNOWN.get(name, "to confirm upstream")
    return found


def _declared(name: str) -> str:
    try:
        meta = metadata.distribution(name).metadata
    except metadata.PackageNotFoundError:
        return "not installed here: check upstream"
    expr = (meta.get("License-Expression") or "").strip()
    if expr:
        return expr
    classes = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::") and "OSI Approved" in c]
    classes = [c for c in classes if c != "OSI Approved"]
    if classes:
        return "; ".join(classes)
    text = (meta.get("License") or "").strip().splitlines()
    first = text[0].strip() if text else ""
    return first if 0 < len(first) <= 60 else "see the package's own metadata"


def main() -> int:
    rows = [f"| {n} | {v} | {license_of(n)} |" for n, v in indirect().items()]
    OUT.write_text(
        "# Third-party packages pulled in by the host\n\n"
        "The host names a few packages itself (see [THIRD-PARTY.md](../../THIRD-PARTY.md)). Each of those pulls in others. This table lists every other package in "
        "`host/uv.lock` with the license its own metadata declares. None is vendored here, and the license texts stay with each package.\n\n"
        "Generated by `scripts/third-party-indirect.py`; `scripts/license-check.py` fails when the lock holds a package with no row.\n\n"
        "| Package | Locked version | License (as the package declares it) |\n|---|---|---|\n" + "\n".join(rows) + "\n"
    )
    print(f"third-party-indirect: {len(rows)} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
